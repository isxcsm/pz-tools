-- Mission rewards, deadlines judged at sealing, the sample cooler (NUMBERS 9).
require "OperationAcorn/Core"
require "OperationAcorn/Story/Rewards"
local OA = OperationAcorn
local R = OA.Rewards

test("levels follow the trust stage, six after a milestone", function()
    eq(R.level(0, 0), nil, "no missions before stage 1")
    eq(R.level(1, 0), 1)
    eq(R.level(4, 0), 4)
    eq(R.level(5, 0), 5)
    eq(R.level(5, 1), 6, "milestone")
    eq(R.level(5, 3), 6)
end)

test("bands and rewards come from the table", function()
    local lo, hi = R.band(1)
    eq(lo, 150); eq(hi, 600)
    lo, hi = R.band(6)
    eq(lo, 2000); eq(hi, 8000)
    local c, t = R.reward(1, false)
    eq(c, 10000); eq(t, 60)
    c, t = R.reward(3, false)
    eq(c, 35000); eq(t, 200)
    c, t = R.reward(2, true)
    eq(c, 30000, "story is x1.5"); eq(t, 180)
    c, t = R.reward(5, true)
    eq(c, 105000); eq(t, 600)
    c, t = R.reward(6, false)
    eq(c, 90000); eq(t, 500)
end)

test("the credit scale applies to credits only", function()
    local c, t = R.reward(1, false, 1, 2)
    eq(c, 20000); eq(t, 60)
end)

test("the deadline is judged when the box is sealed", function()
    eq(R.judge(100, 99.9), "ok")
    eq(R.judge(100, 100), "ok")
    eq(R.judge(100, 100.5), "late")
end)

test("the cooler warms by the hour and the reward slides", function()
    near(R.coolerTemp(0), 4)
    near(R.coolerTemp(4), 6)
    near(R.coolerTemp(1000), 30, 1e-9, "capped")
    near(R.coolerQuality(4), 1.0)
    near(R.coolerQuality(8), 1.0)
    near(R.coolerQuality(12), 0.8)
    near(R.coolerQuality(16), 0.6)
    near(R.coolerQuality(30), 0.6)
    eq(R.coolerGrade(7), "good")
    eq(R.coolerGrade(10), "warm")
    eq(R.coolerGrade(20), "bad")
    -- The cooler's reward at its worst: a 4th stage story mission.
    local c, t = R.reward(4, true, R.coolerQuality(30))
    eq(c, 45000); eq(t, 270)
end)

test("danger pay is the density over 5 per cent, in steps of 5, from 0 to 30 per cent", function()
    near(R.dangerPay(0.22), 0.15, 1e-9, "the Muldraugh police station")
    near(R.dangerPay(0.06), 0, 1e-9, "the outskirts")
    near(R.dangerPay(0.05), 0, 1e-9)
    near(R.dangerPay(0.0749), 0, 1e-9, "under half a step")
    near(R.dangerPay(0.075), 0.05, 1e-9, "half a step rounds up")
    near(R.dangerPay(0.40), 0.30, 1e-9, "at most 30 per cent")
    near(R.dangerPay(5), 0.30, 1e-9)
    near(R.dangerPay(nil), 0, 1e-9)
    near(R.dangerPay(-1), 0, 1e-9)
end)

test("the danger pay and the streak go on the base credits together", function()
    eq(R.withBonus(30000, 0.15, 2), 40500, "30,000 x (1 + 0.15 + 0.20)")
    eq(R.withBonus(30000, 0, 0), 30000)
    eq(R.withBonus(30000, nil, nil), 30000)
    eq(R.withBonus(10000, 0.3, 9), 16000, "both capped at 30 per cent")
end)

test("the scattered samples pay the set's extra, or the share found", function()
    near(R.scatterShare(3, 3), 1.2)
    near(R.scatterShare(2, 2), 1.2)
    near(R.scatterShare(1, 3), 1 / 3, 1e-9)
    near(R.scatterShare(0, 2), 0)
    near(R.scatterShare(1, 0), 0)
end)

test("taking another costs a tenth of the level's trust", function()
    eq(R.rerollCost(2), 12)
    eq(R.rerollCost(3), 20)
    eq(R.rerollCost(1), 6)
    eq(R.rerollCost(6), 50)
    eq(R.rerollCost(9), 0, "no such level")
end)

test("a special request pays the level's credits twice and its trust once, and looks one level further", function()
    local c, t = R.specialReward(3)
    eq(c, 70000); eq(t, 200)
    c, t = R.specialReward(3, 2)
    eq(c, 140000, "the credit scale"); eq(t, 200)
    eq(R.specialBandLevel(3), 4)
    eq(R.specialBandLevel(6), 6)
    eq(R.SPECIAL_DAYS, 14)
    eq(R.SPECIAL_GAP_DAYS, 7)
end)
