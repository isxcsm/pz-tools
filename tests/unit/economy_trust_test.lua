-- Trust: the thresholds, the milestones, the events and the rewards that replace each other.
require "OperationAcorn/Core"
require "OperationAcorn/Store"
require "OperationAcorn/Economy/Trust"
require "OperationAcorn/Economy/Market"
local OA = OperationAcorn
local T = OA.Trust

local function newRecord()
    return OA.Store.ensure("t", "T")
end

test("stage thresholds are NUMBERS 5", function()
    eq(T.stageThreshold(1), 700); eq(T.stageThreshold(2), 2300); eq(T.stageThreshold(3), 5500)
    eq(T.stageThreshold(4), 11500); eq(T.stageThreshold(5), 23000)
end)

test("milestone thresholds widen by 7,000 each", function()
    eq(T.milestoneThreshold(1), 37000)
    eq(T.milestoneThreshold(2), 58000)
    eq(T.milestoneThreshold(3), 86000)
    eq(T.milestoneThreshold(4), 121000)
    eq(T.milestoneThreshold(5), 163000)
    eq(T.milestoneThreshold(6) - T.milestoneThreshold(5), 14000 + 7000 * 5)
end)

test("TrustThresholdMultiplier scales every threshold", function()
    SandboxVars.OperationAcorn.TrustThresholdMultiplier = 0.5
    eq(T.stageThreshold(1), 350)
    eq(T.milestoneThreshold(1), 18500)
    SandboxVars.OperationAcorn.TrustThresholdMultiplier = 2
    eq(T.stageThreshold(5), 46000)
end)

test("levelFor reads stage and milestones off the trust", function()
    local s, m = T.levelFor(0); eq(s, 0); eq(m, 0)
    s, m = T.levelFor(699.9); eq(s, 0)
    s, m = T.levelFor(700); eq(s, 1)
    s, m = T.levelFor(22999); eq(s, 4); eq(m, 0)
    s, m = T.levelFor(23000); eq(s, 5); eq(m, 0)
    s, m = T.levelFor(37000); eq(s, 5); eq(m, 1)
    s, m = T.levelFor(86000); eq(m, 3)
    s, m = T.levelFor(1e7); truthy(m > 10)
end)

test("add keeps decimals and tells the stages it crossed", function()
    local r = newRecord()
    local events = T.add(r, 699.5)
    eq(#events, 0)
    near(r.trade.trust, 699.5)
    events = T.add(r, 0.5)
    eq(#events, 1)
    eq(events[1].kind, "stage"); eq(events[1].stage, 1); eq(events[1].sharedSerums, 0)
    eq(r.trade.stage, 1)
    events = T.add(r, 6000)
    eq(#events, 2, "stages 2 and 3 in one go")
    eq(events[1].stage, 2); eq(events[2].stage, 3)
    eq(events[1].sharedSerums, 1)
    eq(r.trade.sharedSerums, 2)
end)

test("a shared serum for stages 2..5 and every milestone", function()
    local r = newRecord()
    T.add(r, 23000)
    eq(r.trade.stage, 5)
    eq(r.trade.sharedSerums, 4, "stages 2, 3, 4, 5")
    local events = T.add(r, 37000 - 23000)
    eq(#events, 1)
    eq(events[1].kind, "milestone"); eq(events[1].index, 1); eq(events[1].sharedSerums, 1)
    eq(r.trade.sharedSerums, 5)
    events = T.add(r, 86000 - 37000)
    eq(#events, 2)
    truthy(events[2].transfer, "the third milestone is the transfer")
    eq(r.trade.milestones, 3)
    eq(r.trade.sharedSerums, 7)
end)

test("SharedSerumMilestones spaces the milestone serums", function()
    SandboxVars.OperationAcorn.SharedSerumMilestones = 2
    local r = newRecord()
    T.add(r, 23000)
    local before = r.trade.sharedSerums
    T.add(r, 163000 - 23000)
    eq(r.trade.milestones, 5)
    eq(r.trade.sharedSerums - before, 2, "milestones 2 and 4")
end)

test("zero or negative amounts change nothing", function()
    local r = newRecord()
    eq(#T.add(r, 0), 0)
    eq(#T.add(r, -10), 0)
    eq(r.trade.trust, 0)
end)

test("the tier is stage plus milestones", function()
    local r = newRecord()
    eq(T.tier(r), 0)
    T.add(r, 23000); eq(T.tier(r), 5)
    T.add(r, 37000 - 23000); eq(T.tier(r), 6)
end)

test("rewards at the start", function()
    local r = T.rewardsFor(0, 0)
    eq(r.boxCapacity, 50); eq(r.callInterval, 3)
    eq(r.arrival.min, 4); eq(r.arrival.max, 6)
    eq(r.nightDrop, false); eq(r.rate, 0); near(r.requestBonus, 0.5); eq(r.requestCount, 6)
    eq(r.discount, 0); eq(r.trustAccel, 1.0)
    eq(r.cureInterval, 14); eq(r.cureCount, 1); eq(r.delayInterval, 3); eq(r.delayCount, 1)
    eq(r.softerSupply, false); eq(r.terminalGraph, false); eq(r.marketForecast, false)
end)

test("rewards replace each other, they do not add", function()
    near(T.rewardsFor(3, 0).rate, 0.05)
    near(T.rewardsFor(5, 0).rate, 0.10)
    near(T.rewardsFor(5, 2).rate, 0.15)
    near(T.rewardsFor(3, 0).requestBonus, 0.65)
    near(T.rewardsFor(5, 0).requestBonus, 0.80)
    near(T.rewardsFor(5, 2).requestBonus, 1.00)
    near(T.rewardsFor(4, 0).discount, 0.05)
    near(T.rewardsFor(5, 2).discount, 0.10)
    near(T.rewardsFor(5, 1).trustAccel, 1.1)
    near(T.rewardsFor(5, 3).trustAccel, 1.2)
end)

test("rewards by stage: box, calls, arrival, requests", function()
    eq(T.rewardsFor(1, 0).boxCapacity, 50)
    eq(T.rewardsFor(2, 0).boxCapacity, 50)
    eq(T.rewardsFor(3, 0).boxCapacity, 100)
    eq(T.rewardsFor(4, 0).boxCapacity, 100)
    eq(T.rewardsFor(5, 0).boxCapacity, 200)
    eq(T.rewardsFor(5, 1).boxCapacity, 250)
    eq(T.rewardsFor(5, 2).boxCapacity, 300)
    eq(T.rewardsFor(5, 3).boxCapacity, 350)
    eq(T.rewardsFor(5, 4).boxCapacity, 400, "+50 for every milestone after")
    eq(T.rewardsFor(5, 6).boxCapacity, 500)
    eq(T.rewardsFor(2, 0).callInterval, 2)
    eq(T.rewardsFor(3, 0).callInterval, 2)
    eq(T.rewardsFor(4, 0).callInterval, 1.5)
    eq(T.rewardsFor(5, 2).callInterval, 1)
    eq(T.rewardsFor(3, 0).arrival.min, 3); eq(T.rewardsFor(3, 0).arrival.max, 4)
    eq(T.rewardsFor(5, 3).arrival.min, 2); eq(T.rewardsFor(5, 3).arrival.max, 3)
    eq(T.rewardsFor(5, 0).nightDrop, true); eq(T.rewardsFor(4, 0).nightDrop, false)
    eq(T.rewardsFor(2, 0).requestCount, 8)
    eq(T.rewardsFor(5, 0).requestCount, 10)
    eq(T.rewardsFor(5, 2).requestCount, 12)
end)

test("rewards by stage: serum intervals and counts", function()
    eq(T.rewardsFor(1, 0).cureInterval, 14)
    eq(T.rewardsFor(2, 0).cureInterval, 12)
    eq(T.rewardsFor(3, 0).cureInterval, 10)
    eq(T.rewardsFor(4, 0).cureInterval, 8)
    eq(T.rewardsFor(5, 0).cureInterval, 7)
    eq(T.rewardsFor(5, 1).cureCount, 2)
    eq(T.rewardsFor(2, 0).delayInterval, 3)
    eq(T.rewardsFor(3, 0).delayInterval, 2)
    eq(T.rewardsFor(5, 0).delayInterval, 1)
    eq(T.rewardsFor(5, 1).delayCount, 1)
    eq(T.rewardsFor(5, 2).delayCount, 3)
    eq(T.rewardsFor(4, 0).softerSupply, true)
    eq(T.rewardsFor(2, 0).terminalGraph, true)
    eq(T.rewardsFor(3, 0).marketForecast, true)
end)

test("the options set the starting values and the rewards keep their proportion", function()
    SandboxVars.OperationAcorn.CallInterval = 6.0
    SandboxVars.OperationAcorn.RequestBonus = 100
    SandboxVars.OperationAcorn.HelicopterArrivalMin = 8
    SandboxVars.OperationAcorn.HelicopterArrivalMax = 12
    SandboxVars.OperationAcorn.CureSerumInterval = 28
    SandboxVars.OperationAcorn.DelayDrugInterval = 0
    local r0 = T.rewardsFor(0, 0)
    eq(r0.callInterval, 6); near(r0.requestBonus, 1.0); eq(r0.arrival.min, 8); eq(r0.arrival.max, 12)
    eq(r0.cureInterval, 28); eq(r0.delayInterval, 0)
    local r4 = T.rewardsFor(4, 0)
    eq(r4.callInterval, 3, "1.5 days at the default is half of 3")
    eq(T.rewardsFor(5, 0).cureInterval, 14)
    eq(T.rewardsFor(3, 0).delayInterval, 0)
    near(T.rewardsFor(5, 0).requestBonus, 1.6)
end)

test("rewards of a record follow its stage and milestones", function()
    local r = newRecord()
    eq(T.rewards(r).boxCapacity, 50)
    T.add(r, 5500)
    eq(T.rewards(r).boxCapacity, 100)
    T.add(r, 17500 + 14000)
    eq(T.rewards(r).boxCapacity, 250)
end)

test("progress points at the next threshold", function()
    local r = newRecord()
    T.add(r, 1000)
    local p = T.progress(r)
    eq(p.kind, "stage"); eq(p.number, 2); eq(p.from, 700); eq(p.to, 2300)
    T.add(r, 40000)
    p = T.progress(r)
    eq(p.kind, "milestone"); eq(p.number, 2); eq(p.from, 37000); eq(p.to, 58000)
end)

test("a stage entry raises the market through the trust", function()
    local r = newRecord()
    OA.randomFloat = function() return 0 end
    OA.Market.update(0)
    T.add(r, 700)
    near(OA.Market.index("B"), 1.3, 1e-9)
    near(OA.Market.index("G"), 1.3, 1e-9)
end)
