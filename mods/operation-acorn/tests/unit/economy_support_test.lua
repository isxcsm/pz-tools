-- Flight support (Economy/Support): the numbers trust used to raise by itself are upgrades bought with credits, one
-- level at a time; the steps, the rules for asking, the requests, their payment at a settlement and the words.
require "OperationAcorn/Core"
require "OperationAcorn/Store"
require "OperationAcorn/Economy/Trust"
local OA = OperationAcorn
local Sup = OA.Support

-- A record at a trust level (stage and milestones) with some credits and no levels.
local function newRecord(stage, milestones, credits)
    local r = OA.Store.ensure("sup", "Tester")
    r.trade = { credits = credits or 1000000, trust = 0, stage = stage or 0, milestones = milestones or 0,
        bonus = 0, sharedSerums = 0 }
    return r
end

test("the list names ten upgrades in two groups", function()
    local ids = {}
    for _, u in ipairs(Sup.LIST) do ids[#ids + 1] = u.id end
    eq(table.concat(ids, ","), "box,call,arrive,night,rate,discount,reqcount,reqprice,softer,forecast")
    eq(Sup.get("box").group, "heli"); eq(Sup.get("rate").group, "trade")
    eq(Sup.get("nothing"), nil)
    eq(Sup.maxLevel("box"), nil, "the box goes on")
    eq(Sup.maxLevel("call"), 3)
    eq(Sup.maxLevel("night"), 1)
    eq(Sup.maxLevel("nothing"), nil)
end)

test("step 0 is the start value, free and open to all", function()
    local s = Sup.step("box", 0)
    eq(s.value, 50); eq(s.tier, 0); eq(s.price, 0)
    eq(Sup.step("night", 0).value, false)
    eq(Sup.step("arrive", 0).value[1], 4); eq(Sup.step("arrive", 0).value[2], 6)
    near(Sup.step("reqprice", 0).value, 1.0)
end)

test("the steps of the tables: value, the tier that opens it, the price", function()
    local s = Sup.step("box", 1)
    eq(s.value, 100); eq(s.tier, 3); eq(s.price, 30000)
    s = Sup.step("box", 5)
    eq(s.value, 350); eq(s.tier, 8); eq(s.price, 220000)
    s = Sup.step("call", 3)
    eq(s.value, 1); eq(s.tier, 7); eq(s.price, 150000)
    s = Sup.step("arrive", 2)
    eq(s.value[1], 2); eq(s.value[2], 3); eq(s.tier, 8); eq(s.price, 80000)
    s = Sup.step("night", 1)
    eq(s.value, true); eq(s.tier, 5); eq(s.price, 100000)
    s = Sup.step("discount", 2)
    near(s.value, 0.10); eq(s.tier, 7); eq(s.price, 120000)
    s = Sup.step("reqcount", 3)
    eq(s.value, 12); eq(s.tier, 7); eq(s.price, 90000)
    near(Sup.step("reqprice", 3).value, 4 / 3)
    eq(Sup.step("softer", 1).tier, 4); eq(Sup.step("forecast", 1).price, 25000)
end)

test("the box goes on past its table: 50 more a level, a tier and 40,000 more each", function()
    local s = Sup.step("box", 6)
    eq(s.value, 400); eq(s.tier, 9); eq(s.price, 260000)
    s = Sup.step("box", 7)
    eq(s.value, 450); eq(s.tier, 10); eq(s.price, 300000)
    s = Sup.step("box", 10)
    eq(s.value, 600); eq(s.tier, 13); eq(s.price, 420000)
end)

test("a step that does not exist is nil", function()
    eq(Sup.step("call", 4), nil, "past the end of a finished upgrade")
    eq(Sup.step("night", 2), nil)
    eq(Sup.step("box", -1), nil)
    eq(Sup.step("nothing", 1), nil)
end)

test("levelsForTier gives the levels trust alone used to give", function()
    local l = Sup.levelsForTier(0)
    local count = 0
    for _ in pairs(l) do count = count + 1 end
    eq(count, 0, "nothing at the start")
    l = Sup.levelsForTier(3)
    eq(l.box, 1); eq(l.call, 1); eq(l.arrive, 1); eq(l.rate, 1); eq(l.reqcount, 1); eq(l.reqprice, 1)
    eq(l.forecast, 1); eq(l.night, nil); eq(l.discount, nil); eq(l.softer, nil)
    l = Sup.levelsForTier(5)
    eq(l.box, 2); eq(l.call, 2); eq(l.night, 1); eq(l.rate, 2); eq(l.discount, 1); eq(l.reqcount, 2)
    eq(l.reqprice, 2); eq(l.softer, 1); eq(l.arrive, 1)
    l = Sup.levelsForTier(8)
    eq(l.box, 5); eq(l.call, 3); eq(l.arrive, 2); eq(l.rate, 3); eq(l.discount, 2); eq(l.reqcount, 3)
    eq(l.reqprice, 3)
    l = Sup.levelsForTier(11)
    eq(l.box, 8, "the box past its table: levels 6, 7 and 8 at tiers 9, 10 and 11")
end)

test("the numbers of levelsForTier are the numbers of the old tables", function()
    local function box(tier) return OA.Trust.rewardsFor(0, 0, Sup.levelsForTier(tier)).boxCapacity end
    eq(box(2), 50); eq(box(3), 100); eq(box(4), 100); eq(box(5), 200); eq(box(6), 250); eq(box(7), 300)
    eq(box(8), 350); eq(box(9), 400); eq(box(10), 450)
end)

test("a record starts at level 0 and has its value from the level", function()
    local r = newRecord()
    eq(Sup.level(r, "box"), 0)
    eq(Sup.value(r, "box"), 50)
    Sup.levels(r).box = 2
    eq(Sup.level(r, "box"), 2)
    eq(Sup.value(r, "box"), 200)
    eq(Sup.level({}, "box"), 0, "a record without a trade section")
end)

test("setLevel sets a level outright, 0 removes it, and each change bumps the revision", function()
    local r = newRecord()
    eq(r.trade.levelsRev, nil)
    Sup.setLevel(r, "call", 2)
    eq(r.trade.levels.call, 2)
    eq(r.trade.levelsRev, 1)
    Sup.setLevel(r, "call", 0)
    eq(r.trade.levels.call, nil)
    eq(r.trade.levelsRev, 2)
end)

test("canRequest says yes for the next level that trust has opened", function()
    local r = newRecord(3, 0)
    local ok, why = Sup.canRequest(r, "box", 1, true)
    eq(ok, true); eq(why, nil)
end)

test("canRequest: unknown, max, next, pending, tier, debt and field", function()
    local r = newRecord(3, 0)
    local ok, why = Sup.canRequest(r, "nothing", 1, true)
    eq(ok, false); eq(why, "unknown")
    ok, why = Sup.canRequest(r, "call", 4, true)
    eq(ok, false); eq(why, "max", "past the end")
    ok, why = Sup.canRequest(r, "box", 0, true)
    eq(ok, false); eq(why, "max", "level 0 is not a level to buy")
    ok, why = Sup.canRequest(r, "box", nil, true)
    eq(ok, false); eq(why, "max", "no level")
    ok, why = Sup.canRequest(r, "box", 2, true)
    eq(ok, false); eq(why, "next", "not the level after the one it has")
    Sup.setLevel(r, "box", 1)
    ok, why = Sup.canRequest(r, "box", 1, true)
    eq(ok, false); eq(why, "next", "the level it already has")
    ok, why = Sup.canRequest(r, "box", 2, true)
    eq(ok, false); eq(why, "tier", "box 2 opens at tier 5")
    ok, why = Sup.canRequest(r, "rate", 1, true)
    eq(ok, true)
    Sup.pending(r).rate = 1
    ok, why = Sup.canRequest(r, "rate", 1, true)
    eq(ok, false); eq(why, "pending")
    r.trade.credits = -1
    ok, why = Sup.canRequest(r, "call", 1, true)
    eq(ok, false); eq(why, "debt")
    r.trade.credits = 0
    ok, why = Sup.canRequest(r, "call", 1, false)
    eq(ok, false); eq(why, "field", "at a crude terminal")
    ok, why = Sup.canRequest(r, "call", 1, true)
    eq(ok, true, "no credits needed to ask, only to be paid")
end)

test("the tier counts the milestones", function()
    local r = newRecord(5, 4)
    local ok = Sup.canRequest(r, "box", 1, true)
    eq(ok, true)
    Sup.setLevel(r, "box", 5)
    ok = Sup.canRequest(r, "box", 6, true)
    eq(ok, true, "tier 9 opens level 6")
    ok = Sup.canRequest(r, "box", 7, true)
    eq(ok, false, "and only that one")
    Sup.setLevel(r, "box", 6)
    local _, why = Sup.canRequest(r, "box", 7, true)
    eq(why, "tier", "level 7 opens at tier 10")
end)

test("request puts the level among the pending ones; cancel takes it back", function()
    local r = newRecord(3, 0)
    local ok = Sup.request(r, "box", 1, true)
    eq(ok, true)
    eq(r.trade.pendingLevels.box, 1)
    local again, why = Sup.request(r, "box", 1, true)
    eq(again, false); eq(why, "pending")
    local crude, why2 = Sup.request(r, "rate", 1, false)
    eq(crude, false); eq(why2, "field")
    eq(r.trade.pendingLevels.rate, nil, "a refused request leaves nothing")
    eq(Sup.cancel(r, "box"), true)
    eq(r.trade.pendingLevels.box, nil)
    eq(Sup.cancel(r, "box"), false, "nothing to take back")
    eq(Sup.cancel(r, "nothing"), false)
    eq(Sup.request(r, "box", 1, true), true, "it can be asked for again")
end)

test("requests are listed in the screen's order with their prices", function()
    local r = newRecord(8, 0)
    eq(#Sup.requests(r), 0)
    Sup.request(r, "forecast", 1, true)
    Sup.request(r, "discount", 1, true)
    Sup.request(r, "box", 1, true)
    Sup.request(r, "call", 1, true)
    local list = Sup.requests(r)
    eq(#list, 4)
    eq(list[1].id, "box"); eq(list[2].id, "call"); eq(list[3].id, "discount"); eq(list[4].id, "forecast")
    eq(list[1].from, 0); eq(list[1].to, 1); eq(list[1].price, 30000)
    eq(list[2].price, 40000); eq(list[3].price, 50000); eq(list[4].price, 25000)
end)

test("settle pays the requests in order from the balance and applies the levels", function()
    local r = newRecord(8, 0)
    Sup.request(r, "forecast", 1, true)
    Sup.request(r, "box", 1, true)
    Sup.request(r, "call", 1, true)
    local balance, done = Sup.settle(r, 100000)
    eq(balance, 100000 - 30000 - 40000 - 25000)
    eq(#done, 3)
    eq(done[1].id, "box"); eq(done[1].from, 0); eq(done[1].to, 1); eq(done[1].price, 30000); eq(done[1].paid, true)
    eq(done[2].id, "call"); eq(done[2].paid, true)
    eq(done[3].id, "forecast"); eq(done[3].paid, true)
    eq(r.trade.levels.box, 1); eq(r.trade.levels.call, 1); eq(r.trade.levels.forecast, 1)
    eq(#Sup.requests(r), 0, "nothing stays pending")
    eq(Sup.value(r, "box"), 100)
end)

test("settle changes what the record's rewards say", function()
    local r = newRecord(8, 0)
    eq(OA.Trust.rewards(r).boxCapacity, 50)
    eq(OA.Trust.rewards(r).callInterval, 3)
    Sup.request(r, "box", 1, true)
    eq(OA.Trust.rewards(r).boxCapacity, 50, "a request changes nothing yet")
    local rev = r.trade.levelsRev or 0
    Sup.settle(r, 100000)
    truthy((r.trade.levelsRev or 0) > rev, "the revision is bumped")
    eq(OA.Trust.rewards(r).boxCapacity, 100)
    eq(OA.Trust.rewards(r).callInterval, 3, "what was not bought stays")
end)

test("settle leaves a request the balance cannot pay pending, unpaid, and goes on to the next", function()
    local r = newRecord(8, 0)
    Sup.request(r, "box", 1, true)           -- 30,000
    Sup.request(r, "reqcount", 1, true)      -- 20,000
    local balance, done = Sup.settle(r, 25000)
    eq(#done, 2)
    eq(done[1].id, "box"); eq(done[1].paid, false)
    eq(done[2].id, "reqcount"); eq(done[2].paid, true)
    eq(balance, 5000, "only the second was paid")
    eq(r.trade.levels.box, nil)
    eq(r.trade.levels.reqcount, 1)
    eq(r.trade.pendingLevels.box, 1, "the first waits for the next settlement")
    eq(r.trade.pendingLevels.reqcount, nil)
    balance, done = Sup.settle(r, 40000)
    eq(#done, 1); eq(done[1].paid, true)
    eq(balance, 10000)
    eq(r.trade.levels.box, 1)
end)

test("settle never goes into debt: an exact balance pays, one short does not", function()
    local r = newRecord(8, 0)
    Sup.request(r, "box", 1, true)
    local balance, done = Sup.settle(r, 29999)
    eq(balance, 29999); eq(done[1].paid, false)
    balance, done = Sup.settle(r, 30000)
    eq(balance, 0); eq(done[1].paid, true)
end)

test("settle drops a stale request, whose level is no longer the next", function()
    local r = newRecord(8, 0)
    Sup.request(r, "box", 1, true)
    Sup.setLevel(r, "box", 1)               -- the level came by another road (a dev tool, a restored save)
    local balance, done = Sup.settle(r, 100000)
    eq(balance, 100000, "nothing was paid")
    eq(#done, 0, "nothing to report")
    eq(r.trade.pendingLevels.box, nil, "the stale request is gone")
    eq(r.trade.levels.box, 1)
end)

test("settle with nothing pending changes nothing and does not bump the revision", function()
    local r = newRecord(8, 0)
    local balance, done = Sup.settle(r, 777)
    eq(balance, 777); eq(#done, 0)
    eq(r.trade.levelsRev, nil)
end)

test("the endless box can be bought level after level", function()
    local r = newRecord(5, 6)               -- tier 11
    Sup.setLevel(r, "box", 5)
    eq(Sup.request(r, "box", 6, true), true)
    local balance = Sup.settle(r, 300000)
    eq(balance, 300000 - 260000)
    eq(OA.Trust.rewards(r).boxCapacity, 400)
    eq(Sup.request(r, "box", 7, true), true)
    balance = Sup.settle(r, 300000)
    eq(balance, 0)
    eq(OA.Trust.rewards(r).boxCapacity, 450)
end)

test("words: a value and a change as texts to translate", function()
    local t = Sup.valueText("box", 100)
    eq(t.key, "IGUI_OA_Support_V_box"); eq(t.args[1], "100")
    t = Sup.valueText("night", true)
    eq(t.key, "IGUI_OA_Support_night_true"); eq(t.args, nil)
    t = Sup.valueText("arrive", { 3, 4 })
    eq(t.key, "IGUI_OA_Support_V_arrive"); eq(t.args[1], "3"); eq(t.args[2], "4")
    t = Sup.valueText("rate", 0.05)
    eq(t.key, "IGUI_OA_Support_V_rate"); eq(t.args[1], "5", "a percent")
