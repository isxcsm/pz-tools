    eq(c.key, "IGUI_OA_Support_Change")
    eq(c.args[1].key, "IGUI_OA_Support_Name_box")
    eq(c.args[2].key, "IGUI_OA_Support_V_box"); eq(c.args[2].args[1], "50")
    eq(c.args[3].args[1], "100")
end)

test("appliedTitle is nil when nothing was paid", function()
    eq(Sup.appliedTitle(nil), nil)
    eq(Sup.appliedTitle({}), nil)
    eq(Sup.appliedTitle({ { id = "box", from = 0, to = 1, price = 30000, paid = false } }), nil)
end)

local function done(id, paid)
    return { id = id, from = 0, to = 1, price = 1, paid = paid ~= false }
end

test("appliedTitle: one, two and three changes are joined", function()
    local t = Sup.appliedTitle({ done("box") })
    eq(t.key, "IGUI_OA_Title_SupportApplied"); eq(t.style, "notice")
    eq(t.sub, "IGUI_OA_Support_Joined1"); eq(#t.subArgs, 1)
    eq(t.subArgs[1].key, "IGUI_OA_Support_Change")
    t = Sup.appliedTitle({ done("box"), done("call", false), done("rate") })
    eq(t.sub, "IGUI_OA_Support_Joined2", "the unpaid one is not counted")
    eq(#t.subArgs, 2)
    eq(t.subArgs[1].args[1].key, "IGUI_OA_Support_Name_box")
    eq(t.subArgs[2].args[1].key, "IGUI_OA_Support_Name_rate")
    t = Sup.appliedTitle({ done("box"), done("call"), done("rate") })
    eq(t.sub, "IGUI_OA_Support_Joined3"); eq(#t.subArgs, 3)
end)

test("appliedTitle: past three the first three are named and the rest counted", function()
    local t = Sup.appliedTitle({ done("box"), done("call"), done("night"), done("rate"), done("forecast") })
    eq(t.sub, "IGUI_OA_Support_JoinedMore")
    eq(#t.subArgs, 4)
    eq(t.subArgs[1].args[1].key, "IGUI_OA_Support_Name_box")
    eq(t.subArgs[3].args[1].key, "IGUI_OA_Support_Name_night")
    eq(t.subArgs[4], "2", "five applied, three named")
    t = Sup.appliedTitle({ done("box"), done("call"), done("night"), done("rate") })
    eq(t.subArgs[4], "1")
end)

test("the trade.levels upgrade gives an old record the levels its trust had reached", function()
    local r = OA.Store.ensure("old", "Old")
    r.trade = { credits = 0, trust = 0, stage = 3, milestones = 0, bonus = 0, sharedSerums = 0 }
    r.upgrades = {}                          -- a record saved before the upgrade existed
    OA.Store.upgrade(r)
    local want = Sup.levelsForTier(3)
    truthy(r.trade.levels, "levels were made")
    eq(r.trade.levels.box, want.box); eq(r.trade.levels.call, want.call); eq(r.trade.levels.forecast, want.forecast)
    eq(r.trade.levels.night, nil)
    eq(OA.Trust.rewards(r).boxCapacity, 100, "its box stays as it was")
    eq(r.upgrades["trade.levels"], true)
end)

test("the trade.levels upgrade leaves a record that has levels alone", function()
    local r = OA.Store.ensure("new", "New")
    r.trade = { credits = 0, trust = 0, stage = 5, milestones = 2, bonus = 0, sharedSerums = 0, levels = { call = 1 } }
    r.upgrades = {}
    OA.Store.upgrade(r)
    eq(r.trade.levels.call, 1)
    eq(r.trade.levels.box, nil)
    eq(OA.Trust.rewards(r).boxCapacity, 50)
end)
