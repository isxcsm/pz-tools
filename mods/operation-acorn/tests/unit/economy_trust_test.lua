-- Trust: the thresholds, the milestones, the events and the rewards that replace each other.
require "OperationAcorn/Core"
require "OperationAcorn/Store"
require "OperationAcorn/Economy/Trust"
require "OperationAcorn/Economy/Market"
local OA = OperationAcorn
local T = OA.Trust

local function newRecord()
    return OA.Store.ensure("t", "T")
end

test("stage thresholds are NUMBERS 5", function()
    eq(T.stageThreshold(1), 70); eq(T.stageThreshold(2), 230); eq(T.stageThreshold(3), 550)
    eq(T.stageThreshold(4), 1150); eq(T.stageThreshold(5), 2300)
end)

test("milestone thresholds widen by 700 each", function()
    eq(T.milestoneThreshold(1), 3700)
    eq(T.milestoneThreshold(2), 5800)
    eq(T.milestoneThreshold(3), 8600)
    eq(T.milestoneThreshold(4), 12100)
    eq(T.milestoneThreshold(5), 16300)
    eq(T.milestoneThreshold(6) - T.milestoneThreshold(5), 1400 + 700 * 5)
end)

test("TrustThresholdMultiplier scales every threshold", function()
    SandboxVars.OperationAcorn.TrustThresholdMultiplier = 0.5
    eq(T.stageThreshold(1), 35)
    eq(T.milestoneThreshold(1), 1850)
    SandboxVars.OperationAcorn.TrustThresholdMultiplier = 2
    eq(T.stageThreshold(5), 4600)
end)

test("levelFor reads stage and milestones off the trust", function()
    local s, m = T.levelFor(0); eq(s, 0); eq(m, 0)
    s, m = T.levelFor(69.9); eq(s, 0)
    s, m = T.levelFor(70); eq(s, 1)
    s, m = T.levelFor(2299); eq(s, 4); eq(m, 0)
    s, m = T.levelFor(2300); eq(s, 5); eq(m, 0)
    s, m = T.levelFor(3700); eq(s, 5); eq(m, 1)
    s, m = T.levelFor(8600); eq(m, 3)
    s, m = T.levelFor(1e7); truthy(m > 10)
end)

test("add keeps decimals and tells the stages it crossed", function()
    local r = newRecord()
    local events = T.add(r, 69.5)
    eq(#events, 0)
    near(r.trade.trust, 69.5)
    events = T.add(r, 0.5)
    eq(#events, 1)
    eq(events[1].kind, "stage"); eq(events[1].stage, 1); eq(events[1].sharedSerums, 0)
    eq(r.trade.stage, 1)
    events = T.add(r, 600)
    eq(#events, 2, "stages 2 and 3 in one go")
    eq(events[1].stage, 2); eq(events[2].stage, 3)
    eq(events[1].sharedSerums, 1)
    eq(r.trade.sharedSerums, 2)
end)

test("a shared serum for stages 2..5 and every milestone", function()
    local r = newRecord()
    T.add(r, 2300)
    eq(r.trade.stage, 5)
    eq(r.trade.sharedSerums, 4, "stages 2, 3, 4, 5")
    local events = T.add(r, 3700 - 2300)
    eq(#events, 1)
    eq(events[1].kind, "milestone"); eq(events[1].index, 1); eq(events[1].sharedSerums, 1)
    eq(r.trade.sharedSerums, 5)
    events = T.add(r, 8600 - 3700)
    eq(#events, 2)
    truthy(events[2].transfer, "the third milestone is the transfer")
    eq(r.trade.milestones, 3)
    eq(r.trade.sharedSerums, 7)
end)

test("SharedSerumMilestones spaces the milestone serums", function()
    SandboxVars.OperationAcorn.SharedSerumMilestones = 2
    local r = newRecord()
    T.add(r, 2300)
    local before = r.trade.sharedSerums
    T.add(r, 16300 - 2300)
    eq(r.trade.milestones, 5)
    eq(r.trade.sharedSerums - before, 2, "milestones 2 and 4")
end)

test("zero or negative amounts change nothing", function()
    local r = newRecord()
    eq(#T.add(r, 0), 0)
    eq(#T.add(r, -10), 0)
    eq(r.trade.trust, 0)
end)

test("the tier is stage plus milestones", function()
    local r = newRecord()
    eq(T.tier(r), 0)
    T.add(r, 2300); eq(T.tier(r), 5)
    T.add(r, 3700 - 2300); eq(T.tier(r), 6)
end)

test("rewards at the start", function()
    local r = T.rewardsFor(0, 0)
    eq(r.boxCapacity, 50); eq(r.callInterval, 3)
    eq(r.arrival.min, 4); eq(r.arrival.max, 6)
    eq(r.nightDrop, false); eq(r.rate, 0); eq(r.requestCount, 6)
    near(r.requestPrice, 1.0)
    eq(r.requestBonus, nil, "the old request bonus is the request price upgrade now")
    eq(r.discount, 0); eq(r.trustAccel, 1.0)
    eq(r.softerSupply, false); eq(r.marketForecast, false)
    eq(r.backpack, false); eq(r.kits, false); eq(r.transferred, false)
end)

test("without levels every upgrade number stays at its start, whatever the stage", function()
    local r = T.rewardsFor(5, 4)
    eq(r.boxCapacity, 50); eq(r.callInterval, 3)
    eq(r.arrival.min, 4); eq(r.arrival.max, 6)
    eq(r.nightDrop, false); eq(r.rate, 0); eq(r.requestCount, 6); near(r.requestPrice, 1.0)
    eq(r.discount, 0); eq(r.softerSupply, false); eq(r.marketForecast, false)
    eq(r.cureInterval, nil); eq(r.cureCount, nil); eq(r.delayInterval, nil); eq(r.delayCount, nil)
    eq(r.backpack, true, "what trust gives by itself stays")
    eq(r.kits, true)
    eq(r.transferred, true, "the third milestone")
    near(r.trustAccel, 1.2)
end)

test("rewards replace each other, they do not add", function()
    local Sup = OA.Support
    near(T.rewardsFor(3, 0, Sup.levelsForTier(3)).rate, 0.05)
    near(T.rewardsFor(5, 0, Sup.levelsForTier(5)).rate, 0.10)
    near(T.rewardsFor(5, 2, Sup.levelsForTier(7)).rate, 0.15)
    near(T.rewardsFor(4, 0, Sup.levelsForTier(4)).discount, 0.05)
    near(T.rewardsFor(5, 2, Sup.levelsForTier(7)).discount, 0.10)
    near(T.rewardsFor(5, 1).trustAccel, 1.1)
    near(T.rewardsFor(5, 3).trustAccel, 1.2)
end)

test("rewards by stage with the levels trust alone used to give: box, calls, arrival, requests", function()
    local function at(stage, milestones)
        return T.rewardsFor(stage, milestones, OA.Support.levelsForTier(stage + milestones))
    end
    eq(at(1, 0).boxCapacity, 50)
    eq(at(2, 0).boxCapacity, 50)
    eq(at(3, 0).boxCapacity, 100)
    eq(at(4, 0).boxCapacity, 100)
    eq(at(5, 0).boxCapacity, 200)
    eq(at(5, 1).boxCapacity, 250)
    eq(at(5, 2).boxCapacity, 300)
    eq(at(5, 3).boxCapacity, 350)
    eq(at(5, 4).boxCapacity, 400, "+50 for every level after")
    eq(at(5, 6).boxCapacity, 500)
    eq(at(2, 0).callInterval, 2)
    eq(at(3, 0).callInterval, 2)
    eq(at(4, 0).callInterval, 1.5)
    eq(at(5, 2).callInterval, 1)
    eq(at(3, 0).arrival.min, 3); eq(at(3, 0).arrival.max, 4)
    eq(at(5, 3).arrival.min, 2); eq(at(5, 3).arrival.max, 3)
    eq(at(5, 0).nightDrop, true); eq(at(4, 0).nightDrop, false)
    eq(at(2, 0).requestCount, 8)
    eq(at(5, 0).requestCount, 10)
    eq(at(5, 2).requestCount, 12)
    near(at(2, 0).requestPrice, 1.0)
    near(at(3, 0).requestPrice, 1.1)
    near(at(5, 0).requestPrice, 1.2)
    near(at(5, 2).requestPrice, 1.3)
    eq(at(4, 0).softerSupply, true)
    eq(at(3, 0).marketForecast, true)
    eq(at(2, 0).marketForecast, false)
end)

test("rewardsFor takes the levels as they are, whatever the tier", function()
    local r = T.rewardsFor(0, 0, { box = 6, call = 3, night = 1, softer = 1, forecast = 1 })
    eq(r.boxCapacity, 400, "level 6 is past the table")
    eq(r.callInterval, 1)
    eq(r.nightDrop, true); eq(r.softerSupply, true); eq(r.marketForecast, true)
    eq(r.rate, 0, "a level not given is 0")
    eq(T.rewardsFor(0, 0, { box = 7 }).boxCapacity, 450)
end)

test("the options set the starting values and the rewards keep their proportion", function()
    SandboxVars.OperationAcorn.CallIntervalMultiplier = 2
    SandboxVars.OperationAcorn.RequestPrice = 150
    SandboxVars.OperationAcorn.HelicopterArrivalMultiplier = 2
    local r0 = T.rewardsFor(0, 0)
    eq(r0.callInterval, 6); near(r0.requestPrice, 1.5); eq(r0.arrival.min, 8); eq(r0.arrival.max, 12)
    local r4 = T.rewardsFor(4, 0, OA.Support.levelsForTier(4))
    eq(r4.callInterval, 3, "1.5 days at the default is half of 3")
    eq(r4.arrival.min, 6); eq(r4.arrival.max, 8, "3 and 4 at the default, 8 and 12 scaled")
    near(T.rewardsFor(5, 0, OA.Support.levelsForTier(5)).requestPrice, 1.8, 1e-9, "x1.2 of the starting 1.5")
end)

test("the serum interval options are gone from the sandbox", function()
    eq(SandboxVars.OperationAcorn.CureSerumInterval, nil)
    eq(SandboxVars.OperationAcorn.DelayDrugInterval, nil)
end)

test("rewards of a record follow its stage, milestones and levels", function()
    local r = newRecord()
    eq(T.rewards(r).boxCapacity, 50)
    T.add(r, 550)
    eq(T.rewards(r).boxCapacity, 50, "the stage alone no longer widens the box")
    r.trade.levels = OA.Support.levelsForTier(3)
    OA.Support.setLevel(r, "box", 1)
    eq(T.rewards(r).boxCapacity, 100)
    T.add(r, 1750 + 1400)
    eq(T.rewards(r).boxCapacity, 100, "nor does the milestone")
    OA.Support.setLevel(r, "box", 3)
    eq(T.rewards(r).boxCapacity, 250)
end)

test("the rewards of a record are worked out again when its levels change, and kept otherwise", function()
    local r = newRecord()
    local first = T.rewards(r)
    eq(T.rewards(r), first, "cached")
    OA.Support.setLevel(r, "call", 1)
    local second = T.rewards(r)
    truthy(second ~= first)
    eq(second.callInterval, 2)
    eq(T.rewards(r), second, "cached again")
    T.add(r, 70)
    eq(T.rewards(r).stage, 1, "a stage changes it too")
end)

test("two records do not share their rewards", function()
    local a = OA.Store.ensure("a", "A")
    local b = OA.Store.ensure("b", "B")
    OA.Support.setLevel(a, "box", 2)
    eq(T.rewards(a).boxCapacity, 200)
    eq(T.rewards(b).boxCapacity, 50)
end)

test("the label of a milestone counts on from the last stage", function()
    local r = newRecord()
    T.add(r, 2300)
    eq(T.label(r), "IGUI_OA_Econ_Stage_5")
    T.add(r, 3700 - 2300)
    eq(T.label(r), "IGUI_OA_Econ_Stage_Milestone 6")
    T.add(r, 5800 - 3700)
    eq(T.label(r), "IGUI_OA_Econ_Stage_Milestone 7")
end)

test("progress points at the next threshold", function()
    local r = newRecord()
    T.add(r, 100)
    local p = T.progress(r)
    eq(p.kind, "stage"); eq(p.number, 2); eq(p.from, 70); eq(p.to, 230)
    T.add(r, 4000)
    p = T.progress(r)
    eq(p.kind, "milestone"); eq(p.number, 2); eq(p.from, 3700); eq(p.to, 5800)
end)

test("a stage entry raises the market through the trust", function()
    local r = newRecord()
    OA.randomFloat = function() return 0 end
    OA.Market.update(0)
    T.add(r, 70)
    near(OA.Market.index("B"), 1.3, 1e-9)
    near(OA.Market.index("G"), 1.3, 1e-9)
end)
